CREATE TABLE PEDIDOS(
    IdPedido INT PRIMARY KEY IDENTITY(1,1),

    IdUsuario INT NOT NULL,
    IdDireccion INT NULL,
    IdFormaPago INT NOT NULL,
    IdFormaEntrega INT NOT NULL,
    IdEstadoPedido INT NOT NULL,

    FechaCreacion DATETIME NOT NULL,
    FechaEntrega DATETIME NULL,
    Total DECIMAL(10,2) NOT NULL,

    FOREIGN KEY(IdUsuario) REFERENCES USUARIOS(IdUsuario),
    FOREIGN KEY(IdDireccion) REFERENCES DIRECCIONES(IdDireccion),
    FOREIGN KEY(IdFormaPago) REFERENCES FORMASPAGO(IdFormaPago),
    FOREIGN KEY(IdFormaEntrega) REFERENCES FORMASENTREGA(IdFormaEntrega),
    FOREIGN KEY(IdEstadoPedido) REFERENCES ESTADOSPEDIDO(IdEstadoPedido)
);

CREATE TABLE DETALLESPEDIDO(
    IdDetallePedido INT PRIMARY KEY IDENTITY(1,1),

    IdPedido INT NOT NULL,
    IdProducto INT NOT NULL,

    Cantidad INT NOT NULL,
    PrecioUnitario DECIMAL(10,2) NOT NULL,
    Subtotal DECIMAL(10,2) NOT NULL,

    FOREIGN KEY(IdPedido) REFERENCES PEDIDOS(IdPedido),
    FOREIGN KEY(IdProducto) REFERENCES PRODUCTOS(IdProducto)
);
